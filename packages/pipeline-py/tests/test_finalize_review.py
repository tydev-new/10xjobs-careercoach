"""finalize_review: the one review step. 4 independent lens files in, one recorded verdict out."""
import json, re, sqlite3

import yaml

from tests import helpers as T


def fin(home, p, *a):
    return T.cli(home, "finalize-review", p, *a)


def prepared(home, **kw):
    p = T.built_package(home)
    T.seed_job(home, p)
    T.write_lenses(p, **kw)
    return p


def test_pass_records_everything(home):
    p, jid = T.finalized_package(home)
    rv = json.loads((p / "review.json").read_text())
    assert rv["final"] == "PASS" and rv["job_id"] == jid and rv["gap_source"] == "step6"
    assert rv["reconciled"]["tool"] == "finalize_review.py"
    assert "4-lens: PASS" in (p / "README.md").read_text()
    assert "generated by finalize_review.py" in (p / "review-3lens.md").read_text()
    c = sqlite3.connect(home / "jobs.db")
    assert c.execute("SELECT verdict, source FROM package_runs ORDER BY id DESC LIMIT 1").fetchone() == ("PASS", "stamp_review")
    assert not list(p.glob("*.bak")), "no backup copies"
    assert fin(home, p, "--verify").returncode == 0


def test_worst_lens_wins(home):
    p = prepared(home, verdicts={"recruiter": "REVISE"})
    r = fin(home, p)
    assert r.returncode == 2 and json.loads((p / "review.json").read_text())["final"] == "REVISE"
    p2 = T.built_package(home, "ic-acme-robotics-2"); T.seed_job(home, p2, url=T.URL.replace("555555555555", "555555555556"), title="Staff Platform Engineer")
    T.write_lenses(p2, verdicts={"ats": "FAIL", "recruiter": "REVISE"})
    assert fin(home, p2).returncode == 2 and json.loads((p2 / "review.json").read_text())["final"] == "FAIL"


def test_code_gate_failure_folds_into_fail(home):
    p = prepared(home)
    cp = home / "profile" / "claims.yaml"; d = yaml.safe_load(cp.read_text())
    d["years"] = [y for y in d["years"] if y != 2016]          # the resume prints 2016; now nothing backs it
    cp.write_text(yaml.safe_dump(d, sort_keys=False))
    r = fin(home, p)
    rv = json.loads((p / "review.json").read_text())
    assert r.returncode == 2 and rv["final"] == "FAIL" and not rv["gates"]["claims"]["ok"]
    assert any(e.startswith("CODE GATE FAIL claims") for e in rv["edits"])


def refused(home, p, needle):
    r = fin(home, p)
    assert r.returncode == 1 and "REFUSE" in r.stdout and needle in r.stdout, r.stdout
    assert not (p / "review.json").exists(), "a refusal writes nothing"


def test_refuses_builder_run_as_reviewer(home):
    p = prepared(home, ids={l: (f"r-{l}" if l != "ats" else "build-test-1") for l in T.LENSES})
    refused(home, p, "builder run")


def test_refuses_duplicate_reviewer_ids(home):
    p = prepared(home, ids={l: "same-run" for l in T.LENSES})
    refused(home, p, "not distinct")


def test_refuses_stale_lens(home):
    p = prepared(home)
    (p / "cover.txt").write_text((p / "cover.txt").read_text() + "\nP.S. edited after review\n")
    refused(home, p, "STALE")


def test_refuses_missing_lens(home):
    p = prepared(home)
    (p / "reviews" / "recruiter.json").unlink()
    refused(home, p, "MISSING reviews/recruiter.json")


def test_refuses_wrong_package(home):
    p = prepared(home, recruiter={"package": "eng-other"})
    refused(home, p, "PACKAGE")


def test_verify_detects_change_after_finalize(home):
    p, _ = T.finalized_package(home)
    f = p / "reviews" / "ats.json"; d = json.loads(f.read_text()); d["findings"] = []; f.write_text(json.dumps(d))
    r = fin(home, p, "--verify")
    assert r.returncode == 1 and "ats.json changed" in r.stdout


def test_dry_run_writes_nothing(home):
    p = prepared(home)
    r = fin(home, p, "--dry-run")
    assert r.returncode == 0 and "4-lens: PASS" in r.stdout and not (p / "review.json").exists()


def test_schema_decision_enum_is_generic():
    s = json.loads((T.ROOT / "apply" / "tools" / "review_schema.json").read_text())
    found = []
    def walk(o):
        if isinstance(o, dict):
            if isinstance(o.get("decision"), dict) and "enum" in o["decision"]:
                found.append(o["decision"]["enum"])
            for v in o.values(): walk(v)
        elif isinstance(o, list):
            for v in o: walk(v)
    walk(s)
    assert found == [["user_applies_anyway", "flagged_to_user"]], found
