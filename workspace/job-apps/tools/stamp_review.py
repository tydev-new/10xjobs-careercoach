#!/usr/bin/env python3
"""stamp_review.py: RETIRED from the required path 2026-10-21 (simplification, the user approval policy). Optional/legacy tool.
Use finalize_review.py <pkg> (merge 4 lens files + record the verdict); submit_gate.py accepts only its PASS.
Kept runnable for old packages and the apply evals (problems() is the rubric eval harness).

Original (phase 1, 2026-10-20): the writer of a package's PASS stamp.

  python3 stamp_review.py <pkg>            validate review.json, re-run the gates, then stamp README + review-3lens.md
  python3 stamp_review.py <pkg> --verify   same checks, writes nothing (use at submit time); exit 1 if not PASS-ready
  python3 stamp_review.py <pkg> --dry-run  print what it would write

Refuses PASS (exit 1, nothing written) unless ALL of these hold:
  - review.json validates against tools/review_schema.json (lens names are the rubric enum:
    hiring_manager | age_signal_claims | recruiter | ats; 'Claim accuracy' or any other name fails)
  - goal matches lens (hiring_manager=fit, age_signal_claims=blockers, recruiter/ats=messaging)
  - each of the 4 lenses appears exactly once for the resume, and once for the cover when cover=attached
  - every lens verdict is Pass and final is PASS; round within the configured limit; otherwise escalate to the user
  - hiring_manager names top_rejection_reason and answered=true
  - resume ATS lens: 8-12 keywords; hits/coverage/top3/max_jd_copy_run match what ats_check.py recomputes;
    coverage >= 0.85; top 3 all hit; max_jd_copy_run < 8
  - format lint exits 0 now, and review.json lint_version == the live LINT_VERSION
  - check_claims.py PASS now, and claims_version == the live claims.yaml version
  - gap_check.py PASS: every step-6 gap/blocker tagged; adjacent_shown cites a real claims.yaml id; no overclaim
  - rubric_version == the Version line of <apps-workspace>/rework/apply-rubric.md
REVISE / FAIL reviews are stamped as such (still validated) so the README never shows a stale PASS.

Independent reviews (2026-10-21, the user approval policy): a NEW PASS stamp also needs review.json to come from
reconcile_reviews.py, merging 4 lens files (<pkg>/reviews/<lens>.json) by 4 distinct reviewer runs, none of them the
builder run, same rubric version, reviewing the current files; the merge must still reproduce from the lens files.
--verify on an older package whose review.json has no `reconciled` block still verifies (warning: LEGACY single-pass
review) so packages stamped before 2026-10-21 keep working at submit time; a reconciled review.json is fully re-checked.
"""

# Portable path/config adapter; pipeline implementation below is retained.
from pathlib import Path as _JobbiPath
import os as _jobbi_os, sys as _jobbi_sys
_JOBBI_ROOT = _JobbiPath(_jobbi_os.environ.get("JOBBI_ROOT", str(_JobbiPath(__file__).resolve().parents[3])))
_jobbi_sys.path.insert(0, str(_JOBBI_ROOT))
from runtime_config import policy as _jobbi_policy, candidate as _jobbi_candidate
_JOBBI_SEARCH = _JOBBI_ROOT / "workspace" / "job-search"
_JOBBI_APPS = _JOBBI_ROOT / "workspace" / "job-apps"
_JOBBI_POLICY = _jobbi_policy(_JOBBI_ROOT)
_JOBBI_CAND = _jobbi_candidate(_JOBBI_ROOT)

import argparse, datetime as dt, json, re, subprocess, sys
from pathlib import Path
import jsonschema
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE)); sys.path.insert(0, str(_JOBBI_APPS / 'lib'))
import ats_check, gap_check, reconcile_reviews
import claims as CL

RUBRIC_PATH = Path(str(_JOBBI_APPS / 'rework/apply-rubric.md'))   # the live apply review standard (eval-gated)
def live_rubric_version():
    m = re.search(r"^Version:\s*`?(apply-rubric-[\w.-]+)`?", RUBRIC_PATH.read_text(), re.M)
    return m.group(1)
RUBRIC_VERSION = live_rubric_version()
LENS_GOAL = {"hiring_manager": "fit", "age_signal_claims": "blockers", "recruiter": "messaging", "ats": "messaging"}
LENS_LABEL = {"hiring_manager": "Hiring manager", "age_signal_claims": "Age signal and claims", "recruiter": "Recruiter", "ats": "ATS"}
BEGIN, END = "<!-- review.json:begin (generated by stamp_review.py; do not edit) -->", "<!-- review.json:end -->"

def live_lint_version():
    src = (HERE / "lint_3lens_package.py").read_text()
    return re.search(r'^LINT_VERSION\s*=\s*"([^"]+)"', src, re.M).group(1)

def problems(pkg, rv):
    errs = []
    schema = json.loads((HERE / "review_schema.json").read_text())
    try:
        jsonschema.validate(rv, schema)
    except jsonschema.ValidationError as e:
        path = "/".join(str(x) for x in e.absolute_path)
        return [f"SCHEMA {path or '(root)'}: {e.message}"]
    docs = ["resume"] + (["cover"] if rv["cover"] == "attached" else [])
    for doc in docs:
        for lens in LENS_GOAL:
            n = sum(1 for l in rv["lenses"] if l["lens"] == lens and l["doc"] == doc)
            if n != 1:
                errs.append(f"LENS {lens} on {doc}: found {n}, need exactly 1")
    for l in rv["lenses"]:
        if l["goal"] != LENS_GOAL[l["lens"]]:
            errs.append(f"GOAL {l['lens']}/{l['doc']}: goal {l['goal']!r} should be {LENS_GOAL[l['lens']]!r}")
        if l["doc"] == "cover" and rv["cover"] == "none":
            errs.append(f"COVER {l['lens']}: cover lens present but cover=none")
    verdicts = {(l["lens"], l["doc"]): l["verdict"] for l in rv["lenses"]}
    final = rv["final"]
    if final == "PASS":
        bad = [f"{k[0]}/{k[1]}={v}" for k, v in verdicts.items() if v != "Pass"]
        if bad:
            errs.append("VERDICT final PASS but lenses not all Pass: " + ", ".join(bad))
        if rv["round"] > (_JOBBI_POLICY.get("max_review_rounds") or 0):
            errs.append(f"ROUND {rv['round']}: configured fix-round limit exceeded; escalate to the user instead of stamping PASS")
    hm = [l for l in rv["lenses"] if l["lens"] == "hiring_manager" and l["doc"] == "resume"]
    if hm and (not hm[0].get("top_rejection_reason") or ("answered" not in hm[0])):
        errs.append("HM resume lens must name top_rejection_reason and set answered")
    if final == "PASS" and hm and hm[0].get("answered") is not True:
        errs.append("HM top rejection reason is not answered")
    ats = [l for l in rv["lenses"] if l["lens"] == "ats" and l["doc"] == "resume"]
    if ats:
        a = ats[0]
        kws = a.get("keywords") or []
        if not 8 <= len(kws) <= 12:
            errs.append(f"ATS needs 8-12 must-have keywords, got {len(kws)}")
        if kws:
            calc = ats_check.compute(pkg, kws)
            for got, want in zip(kws, calc["keywords"]):
                if got["hit"] != want["hit"]:
                    errs.append(f"ATS keyword {got['term']!r}: review says hit={got['hit']}, resume text says {want['hit']}")
            if abs(a.get("coverage", -1) - calc["coverage"]) > 0.01:
                errs.append(f"ATS coverage: review says {a.get('coverage')}, recomputed {calc['coverage']}")
            if a.get("top3_hit") != calc["top3_hit"]:
                errs.append(f"ATS top3_hit: review says {a.get('top3_hit')}, recomputed {calc['top3_hit']}")
            if a.get("max_jd_copy_run") != calc["max_jd_copy_run"]:
                errs.append(f"ATS max_jd_copy_run: review says {a.get('max_jd_copy_run')}, recomputed {calc['max_jd_copy_run']} ({calc['max_jd_copy_text']!r})")
            if final == "PASS":
                if calc["coverage"] < 0.85:
                    errs.append(f"ATS coverage {calc['coverage']:.0%} < 85%")
                if not calc["top3_hit"]:
                    errs.append("ATS top 3 must-haves not all present")
                if calc["max_jd_copy_run"] >= 8:
                    errs.append(f"ATS copied JD run of {calc['max_jd_copy_run']} words: {calc['max_jd_copy_text']!r}")
    llv = live_lint_version()
    if rv["lint_version"] != llv:
        errs.append(f"LINT review.json says {rv['lint_version']!r}, live lint is {llv!r} (stale: re-lint and re-check)")
    lint = subprocess.run([sys.executable, str(HERE / "lint_3lens_package.py"), str(pkg)], capture_output=True, text=True)
    if lint.returncode != 0:
        errs.append("LINT format lint FAILS now:\n    " + "\n    ".join(l for l in lint.stdout.splitlines() if "FAIL" in l)[:1500])
    cv = CL.load()["version"]
    if rv["claims_version"] != cv:
        errs.append(f"CLAIMS review.json says {rv['claims_version']!r}, live claims.yaml is {cv!r}")
    cc = subprocess.run([sys.executable, str(HERE / "check_claims.py"), str(pkg)], capture_output=True, text=True)
    if cc.returncode != 0:
        errs.append("CLAIMS check_claims FAILS now:\n    " + "\n    ".join(l.strip() for l in cc.stdout.splitlines() if "FAIL" in l)[:1500])
    gfails, _ = gap_check.check(pkg, rv)
    errs += ["GAP " + f for f in gfails]
    if rv["rubric_version"] != RUBRIC_VERSION:
        errs.append(f"RUBRIC review.json says {rv['rubric_version']!r}, current is {RUBRIC_VERSION!r}")
    return errs

def render(rv, stamp):
    out = [BEGIN, "## Structured review (review.json)", "", f"**{stamp}**", "", "This block supersedes any earlier Final gate or lens table above.", "",
           f"Base: `{rv['base']}` · round {rv['round']} · {rv['lint_version']} · {rv['claims_version']} · {rv['rubric_version']}", "",
           "| Lens | Goal | Doc | Verdict | Why |", "|---|---|---|---|---|"]
    for l in rv["lenses"]:
        out.append(f"| {LENS_LABEL[l['lens']]} | {l['goal']} | {l['doc']} | {l['verdict']} | {'; '.join(l['reasons'])} |")
    hm = next((l for l in rv["lenses"] if l["lens"] == "hiring_manager" and l["doc"] == "resume"), None)
    if hm:
        out += ["", f"HM top rejection reason: {hm.get('top_rejection_reason')} (answered: {hm.get('answered')})"]
    ats = next((l for l in rv["lenses"] if l["lens"] == "ats" and l["doc"] == "resume"), None)
    if ats and ats.get("keywords"):
        out += ["", f"ATS keywords ({ats['coverage']:.0%} coverage, top 3 hit: {ats['top3_hit']}, longest JD copy run: {ats['max_jd_copy_run']} words):"]
        out += [f"- {'[x]' if k['hit'] else '[ ]'} {k['term']}" + (f" ({' | '.join(k['aliases'])})" if k['aliases'] else "") for k in ats["keywords"]]
    if rv.get("gap_handling") is not None:
        out += ["", f"Gap handling (source: {rv.get('gap_source', 'step6')}):"]
        out += [f"- {g['kind']} '{g['item']}': {g['handling']}" + (f" ({g['claim_id']})" if g.get("claim_id") else "")
                + (f" [{g['decision']}]" if g.get("decision") else "") + f": {g['reason']}" for g in rv["gap_handling"]] or ["- none in the step-6 record"]
    if rv.get("edits"):
        out += ["", "Edits:"] + [f"- {e}" for e in rv["edits"]]
    if rv.get("residual_gaps"):
        out += ["", "Residual gaps (for the digest):"] + [f"- {g}" for g in rv["residual_gaps"]]
    out.append(END)
    return "\n".join(out)

def write_stamp(pkg, rv, stamp):
    rd = pkg / "README.md"
    txt = rd.read_text() if rd.exists() else f"# {pkg.name}\n"
    line = f"- **{stamp}**"
    if re.search(r"(?m)^.*[34]-lens:.*$", txt):
        txt = re.sub(r"(?m)^.*[34]-lens:.*$", line.replace("\\", "\\\\"), txt, count=1)
    else:
        txt = txt.rstrip("\n") + "\n" + line + "\n"
    rd.write_text(txt)
    rf = pkg / "review-3lens.md"
    body = rf.read_text() if rf.exists() else f"# Review: {pkg.name}\n"
    block = render(rv, stamp)
    if BEGIN in body:
        body = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda m: block, body, flags=re.S)
    else:
        body = body.rstrip("\n") + "\n\n" + block + "\n"
    rf.write_text(body)

def record_run(pkg, rv, final):
    """outcome traceability (phase 2): one package_runs row per stamp in pipeline/jobs.db."""
    import os
    db = os.environ.get("STAMP_REVIEW_DB")           # tests point this at a temp DB
    if not db and not str(pkg).startswith(str(_JOBBI_APPS)):
        print("  package_runs: skipped (package outside <apps-workspace>; set STAMP_REVIEW_DB to record)"); return
    try:
        sys.path.insert(0, str(_JOBBI_SEARCH / 'pipeline'))
        import jobsdb as J, pkgmeta as PM
        with J.locked():
            c = J.connect(db) if db else J.connect()
            rid = J.record_package_run(c, package_path=str(pkg), job_id=rv.get("job_id"), base=rv["base"],
                                       cover_format=PM.cover_format(pkg), lint_version=rv["lint_version"],
                                       claims_version=rv["claims_version"], rubric_version=rv["rubric_version"],
                                       verdict=final, round=rv["round"], stamped_at=J.now_iso(), source="stamp_review")
            c.commit()
        print(f"  package_runs #{rid} recorded in jobs.db")
    except Exception as e:   # never lose a stamp because the DB is busy; report it instead
        print(f"  WARN package_runs not recorded: {e}")

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("pkg"); ap.add_argument("--verify", action="store_true"); ap.add_argument("--dry-run", action="store_true")
    a = ap.parse_args()
    print("note: stamp_review.py is retired from the required path; use finalize_review.py (2026-10-21)", file=sys.stderr)
    pkg = Path(a.pkg).resolve()
    rj = pkg / "review.json"
    if not rj.exists():
        print(f"REFUSE: {rj} missing (reviews must be structured JSON)"); sys.exit(1)
    try:
        rv = json.loads(rj.read_text())
    except json.JSONDecodeError as e:
        print(f"REFUSE: review.json is not valid JSON: {e}"); sys.exit(1)
    errs = problems(pkg, rv)
    final = rv.get("final", "?")
    legacy = "reconciled" not in rv
    if not legacy:
        errs += reconcile_reviews.verify(pkg, rv)
    elif final == "PASS" and not a.verify:
        errs.append("INDEPENDENT a new PASS stamp needs 4 independent lens reviews merged by reconcile_reviews.py "
                    "(reviews/<lens>.json from 4 separate reviewer runs, none the builder); this review.json is single-pass")
    if errs:
        print(f"REFUSE {pkg.name}: {len(errs)} problem(s)")
        for e in errs: print("  -", e)
        sys.exit(1)
    today = dt.datetime.now().strftime("%Y-%m-%d")
    stamp = f"4-lens: {final} ({today}; {rv['lint_version']}; {rv['claims_version']}; {RUBRIC_VERSION}; review.json round {rv['round']})"
    if a.verify:
        if legacy: print(f"WARNING {pkg.name}: LEGACY single-pass review (stamped before independent lens reviews); not re-reviewed")
        print(f"VERIFIED {pkg.name}: {final} still holds under the live lint, claims and rubric"); sys.exit(0 if final == "PASS" else 1)
    if a.dry_run:
        print(stamp); print(render(rv, stamp)); sys.exit(0)
    write_stamp(pkg, rv, stamp)
    record_run(pkg, rv, final)
    print(f"STAMPED {pkg.name}: {stamp}")
    print(f"  next: python3 <search-workspace>/pipeline/update_status.py --url <job url> --status Packaged --package {pkg} --by <agent>")
    sys.exit(0 if final == "PASS" else 2)

if __name__ == "__main__":
    main()
